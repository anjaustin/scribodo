#!/usr/bin/env python3
"""Writes src/llm/observer_unicode_word.h: the code points at or above U+0080 that Python's re matches with \\w in a str
pattern (str.isalnum() or "_"), as sorted inclusive ranges, so the C ports of the observer's rules
(src/llm/observer_text.c py_word_at) read a word boundary as the Python they were ported from does, for every script
(red-team 2026-11-15: a hand-written test called x, emoji and fullwidth punctuation word characters).

usage: tools/gen_unicode_word.py > src/llm/observer_unicode_word.h
The table records the Unicode version of the Python that wrote it; tests/test_observer_rules.py checks it against the
running Python and says so when the versions differ."""
import re
import sys
import unicodedata


def ranges():
    word = re.compile(r"\w")
    out, start = [], None
    for c in range(0x80, 0x110000):
        ok = not 0xD800 <= c <= 0xDFFF and bool(word.match(chr(c)))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    rs = ranges()
    print("/* Generated by tools/gen_unicode_word.py; do not edit. Python %s, Unicode %s." % (
        sys.version.split()[0], unicodedata.unidata_version))
    print(" * The code points >= U+0080 that Python's re \\w matches in a str pattern, as sorted inclusive ranges. */")
    print("#define OBS_UNICODE_WORD_VERSION \"%s\"" % unicodedata.unidata_version)
    print("static const unsigned int k_unicode_word[][2] = {")
    for i in range(0, len(rs), 4):
        print("    " + " ".join("{ 0x%04X, 0x%04X }," % r for r in rs[i:i + 4]))
    print("};")
    return 0


if __name__ == "__main__":
    sys.exit(main())
