#!/usr/bin/env python3
"""Generate the boundary-question UI script from a boundary fixture.

    python3 tools/answer_boundary_script.py FIXTURE.json OUTPUT.scribo [--check]

The script attaches the eight parts of an imported novel to the fixture chat,
enables memory, and asks each case's question in fixture order; a case's
history notes are typed as their own turns first. Every designated passage
becomes an `expect memory_sources` check on the first 40 characters of the
passage, so the script checks source delivery only; reply quality is reviewed
afterwards (tools/answer_pipeline_review.py). With --check the generated text
is compared with OUTPUT and the exit status says whether they match, so the
test suite can hold a script to its fixture. Deterministic.
"""
import json
import sys
from pathlib import Path

HEADER = """# Boundary questions (manifold cycle step 2): fresh source-bound cases written
# before any model run; see {fixture}. Each
# question is checked only for source delivery (memory_sources carries the
# designated passage). Reply quality is reviewed afterwards against the fixture's
# fields; the novel's answer vocabulary is never the pass oracle here.
# Generated by tools/answer_boundary_script.py; edit the fixture, not this file.
# Run: SCRIBODO_PRODUCT_SCRIPT={script} \\
#      SCRIBODO_MANUSCRIPT={manuscript} \\
#      python3 tools/answer_product_run.py <label> <live-capture app binary>
"""

PREAMBLE = """wait 5
dialog "$DIR/manuscript"
click_element WelcomeOpen
wait_status "now kept in the project store" 1800
expect explorer_has "Manuscript chat"
click_element ChatItem0
wait_history
# Attach every part (the menu lists the project's documents in explorer order).
click_element AttachAdd
click_element MenuItem0
click_element AttachAdd
click_element MenuItem1
click_element AttachAdd
click_element MenuItem2
click_element AttachAdd
click_element MenuItem3
click_element AttachAdd
click_element MenuItem4
click_element AttachAdd
click_element MenuItem5
click_element AttachAdd
click_element MenuItem6
click_element AttachAdd
click_element MenuItem7
expect attached "part01.md,part02.md,part03.md,part04.md,part05.md,part06.md,part07.md,part08.md"
# Memory over the chat and the eight attached parts.
expect memory_enabled no
measure_frames start
right_click_element ChatItem0
click_element MenuItem2
wait_memory 402 36000
wait_memory_documents 8 36000
measure_frames stop
expect memory_enabled yes
wait_ready 36000
"""

PASSAGE_CHARS = 40


def turn(text):
    return f'click_element ChatInput\ntype "{text}"\nkey ENTER\nwait_chat 14400\nexpect chat_busy no\n'


def generate(fixture, fixture_path, script_path):
    manuscript = fixture.get('manuscript', 'build/manuscripts/pride-and-prejudice/parts')
    out = [HEADER.format(fixture=fixture_path, script=script_path, manuscript=manuscript), PREAMBLE]
    for case in fixture['cases']:
        block = f"# {case['id']} ({case['kind']})\n"
        for note in case.get('history', []):
            block += turn(note['content'])
        block += turn(case['question'])
        for d in case['designated']:
            block += f'expect memory_sources "{d["passage"][:PASSAGE_CHARS]}"\n'
        out.append(block)
    return '\n'.join(out)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    if len(args) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    fixture_path, script_path = Path(args[0]), Path(args[1])
    text = generate(json.loads(fixture_path.read_text()), fixture_path.as_posix(), script_path.as_posix())
    if '--check' in sys.argv:
        current = script_path.read_text() if script_path.exists() else None
        if current == text:
            print(f'{script_path}: matches {fixture_path}')
            return 0
        print(f'{script_path}: differs from what {fixture_path} generates', file=sys.stderr)
        return 1
    script_path.write_text(text)
    print(f'wrote {script_path} ({len(text.splitlines())} lines)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
