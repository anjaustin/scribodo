#!/usr/bin/env python3
"""Prove a GGUF holds exactly the official LFM3 BF16 weights (see docs/MODEL-001).

For every tensor in the GGUF, find an original safetensors tensor in the same
layer with the identical bit pattern: first in the same order (exact), and
failing that as the same multiset of values (reordered by the converter).
F32 tensors must be lossless widenings of BF16 (low 16 bits all zero).

Also prints the GGUF's SHA-256, which the app pins before launching the
server, and a tensor-type census.

Usage: build/venv-model/bin/python tools/model_check/gguf_identity.py [gguf-file-name]
Exit status is non-zero unless every original tensor is accounted for.
"""
import collections
import hashlib
import json
import os
import re
import struct
import sys

import numpy as np
from gguf import GGUFReader
from huggingface_hub import hf_hub_download

sys.path.insert(0, os.path.dirname(__file__))
import lfm3_check as base  # noqa: E402


def main():
    gguf_file = sys.argv[1] if len(sys.argv) > 1 else base.GGUF_FILE
    st = hf_hub_download(base.REPO, "model.safetensors", revision=base.REV)
    gg = hf_hub_download(base.GGUF_REPO, gguf_file, revision=base.GGUF_REV)

    with open(st, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        hdr = json.loads(f.read(n))
    start = 8 + n
    hdr.pop("__metadata__", None)
    if any(v["dtype"] != "BF16" for v in hdr.values()):
        print("FAIL: original checkpoint is not all-BF16")
        return 1
    mm = np.memmap(st, dtype=np.uint8, mode="r")

    def fingerprints(bits):
        return (hashlib.sha256(bits.tobytes()).hexdigest(),
                hashlib.sha256(np.sort(bits).tobytes()).hexdigest())

    def layer(name):
        m = re.search(r"\.(\d+)\.", name)
        return m.group(1) if m else "global"

    pool = collections.defaultdict(dict)
    for name, info in hdr.items():
        a, b = info["data_offsets"]
        pool[layer(name)][name] = fingerprints(np.frombuffer(mm[start + a:start + b], dtype=np.uint16))

    reader = GGUFReader(gg)
    census = collections.Counter(t.tensor_type.name for t in reader.tensors)
    exact = reordered = 0
    used, unmatched, not_widening = set(), [], []
    for t in reader.tensors:
        if t.name == "rope_freqs.weight":  # generated by the converter, not a weight
            continue
        kind = t.tensor_type.name
        if kind == "BF16":
            bits = np.asarray(t.data).view(np.uint16).reshape(-1)
        elif kind == "F32":
            raw = np.asarray(t.data, dtype=np.float32).view(np.uint32).reshape(-1)
            if np.any(raw & 0xFFFF):
                not_widening.append(t.name)
            bits = (raw >> 16).astype(np.uint16)
        else:
            unmatched.append("%s (%s)" % (t.name, kind))
            continue
        e, m = fingerprints(bits)
        cands = pool[layer(t.name.replace("blk.", "x."))]
        hit = next((k for k, (se, _) in cands.items() if k not in used and se == e), None)
        how = "exact"
        if hit is None:
            hit = next((k for k, (_, sm) in cands.items() if k not in used and sm == m), None)
            how = "reordered"
        if hit is None:
            unmatched.append(t.name)
            continue
        used.add(hit)
        exact += how == "exact"
        reordered += how == "reordered"

    print("gguf:", gguf_file, "@", base.GGUF_REV[:8])
    print("sha256:", base.sha256_file(gg))
    print("tensor types:", dict(census))
    print("matched to original: exact %d, reordered %d" % (exact, reordered))
    print("F32 tensors that are not lossless BF16 widenings:", not_widening or "none")
    missing = [k for k in hdr if k not in used]
    print("unmatched GGUF tensors:", unmatched or "none")
    print("original tensors not found in GGUF:", missing or "none")
    ok = not unmatched and not missing and not not_widening
    print("RESULT:", "IDENTICAL (bit-exact BF16 weights)" if ok else "NOT IDENTICAL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
